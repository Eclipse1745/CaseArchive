
create table if not exists cases (
  id            int generated always as identity primary key,
  workspace_id  text not null,
  case_number   text not null,
  title         text not null,
  description   text not null default '',
  status        text not null default 'Under Investigation',
  created_by    text not null,
  created_at    timestamptz not null default now()
);
create index if not exists cases_ws_idx on cases (workspace_id, created_at desc);

create table if not exists documents (
  id               int generated by default as identity primary key,
  workspace_id     text not null,
  case_id          int not null references cases(id) on delete cascade,
  doc_type         text not null,
  title            text not null,
  uploader         text not null,
  -- Stored as text on purpose: the exact ISO string is part of the block-hash input.
  sealed_at        text not null,
  file_name        text not null,
  file_type        text not null,
  original_hash    text not null,
  chain_index      int  not null,
  prev_block_hash  text not null,
  block_hash       text not null,
  unique (case_id, chain_index)
);
create index if not exists documents_ws_case_idx on documents (workspace_id, case_id);

create table if not exists evidence (
  id                 int generated always as identity primary key,
  workspace_id       text not null,
  case_id            int not null references cases(id) on delete cascade,
  evidence_number    text not null,
  item_type          text not null,
  description        text not null,
  status             text not null,
  current_custodian  text not null,
  current_location   text not null,
  logged_by          text not null,
  logged_at          timestamptz not null default now(),
  custody_log        jsonb not null default '[]'::jsonb
);
create index if not exists evidence_ws_case_idx on evidence (workspace_id, case_id);

create table if not exists audit_log (
  id            int generated always as identity primary key,
  workspace_id  text not null,
  case_id       int,
  document_id   int,
  evidence_id   int,
  actor_role    text not null,
  actor_name    text not null,
  action        text not null,
  details       text not null,
  ts            timestamptz not null default now()
);
create index if not exists audit_ws_case_idx on audit_log (workspace_id, case_id, ts desc);

-- Lock the tables: only the server (service role key) can read or write.
alter table cases     enable row level security;
alter table documents enable row level security;
alter table evidence  enable row level security;
alter table audit_log enable row level security;

-- The block hash includes the document id, so the server needs the id before inserting.
create or replace function public.next_document_id()
returns int language sql security definer set search_path = public as $$
  select nextval(pg_get_serial_sequence('public.documents', 'id'))::int
$$;
revoke all on function public.next_document_id() from public, anon, authenticated;
grant execute on function public.next_document_id() to service_role;

-- Private bucket for the uploaded files (or create "case-files" by hand in Storage).
insert into storage.buckets (id, name, public)
values ('case-files', 'case-files', false)
on conflict (id) do nothing;
